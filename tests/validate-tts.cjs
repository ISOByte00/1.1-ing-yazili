'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const page=fs.readFileSync(path.join(root,'index.html'),'utf8');
const engine=fs.readFileSync(path.join(root,'tts.js'),'utf8');
const workflow=fs.readFileSync(path.join(root,'.github/workflows/generate-voice-pack.yml'),'utf8');
const generator=fs.readFileSync(path.join(root,'scripts/generate-audio.mjs'),'utf8');
assert(page.includes('src="tts.js"') && page.indexOf('src="tts.js"')<page.indexOf('src="app.js"'));
assert(engine.includes("mode: 'en', provider: 'recorded'"));
assert(app.includes('voice-provider') && !app.includes('voice-endpoint'));
assert(app.includes('StudyVoice.say(content,lang,ui.voiceRate,engineToken)'));
assert(workflow.includes('workflow_dispatch')&&!workflow.includes('schedule:'));
assert(workflow.includes('secrets.GOOGLE_TTS_API_KEY') && workflow.includes('contents: write'));
assert(generator.includes('MAX_SYNTHESIS_REQUESTS = 34'));
assert(generator.includes('MAX_BILLABLE_CHARACTERS = 1200'));
assert(!page.includes('API_KEY') && !engine.includes('texttospeech.googleapis.com'));
assert(!app.includes('workers.dev'));
console.log('PASS: static MP3 audio engine, manual generation, safe fallback, no live Cloud endpoint.');